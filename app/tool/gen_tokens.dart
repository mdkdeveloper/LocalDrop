// Generates lib/theme/tokens.g.dart from ../design/tokens.json.
//
// The design file is the source of truth for colours (exported by
// design/tools/styled.py). Run after changing the tokens:
//
//   dart run tool/gen_tokens.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final root = File.fromUri(Platform.script).parent.parent;
  final src = File('${root.path}/../design/tokens.json');
  final out = File('${root.path}/lib/theme/tokens.g.dart');
  final json = jsonDecode(src.readAsStringSync()) as Map<String, dynamic>;
  final colors = json['colors'] as Map<String, dynamic>;

  String field(String token) {
    // color/surface-2 -> surface2, color/on-accent -> onAccent
    final parts = token.split('/').last.split('-');
    return parts.first +
        parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
  }

  String argb(String hex) => '0xFF${hex.substring(1).toUpperCase()}';

  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from design/tokens.json.')
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln("import 'dart:ui';")
    ..writeln()
    ..writeln(
      '/// Colour tokens of the LocalDrop design (collection "${json['collection']}").',
    )
    ..writeln('class LdColors {')
    ..writeln('  const LdColors({');
  for (final k in colors.keys) {
    b.writeln('    required this.${field(k)},');
  }
  b.writeln('  });');
  b.writeln();
  for (final e in colors.entries) {
    b.writeln('  /// ${(e.value as Map)['use']}.');
    b.writeln('  final Color ${field(e.key)};');
  }
  for (final mode in ['light', 'dark']) {
    b.writeln();
    b.writeln('  /// Mode ${mode[0].toUpperCase()}${mode.substring(1)}.');
    b.writeln('  static const $mode = LdColors(');
    for (final e in colors.entries) {
      b.writeln(
        '    ${field(e.key)}: Color(${argb((e.value as Map)[mode] as String)}),',
      );
    }
    b.writeln('  );');
  }
  b.writeln('}');
  out.parent.createSync(recursive: true);
  out.writeAsStringSync(b.toString());
  Process.runSync(Platform.resolvedExecutable, ['format', out.path]);
  stdout.writeln('wrote ${out.path} (${colors.length} colours)');
}
