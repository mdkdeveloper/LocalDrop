//! Miscellaneous identifiers.

use std::fmt;
use std::str::FromStr;

use rand::RngCore;
use serde::{Deserialize, Serialize};

macro_rules! random_id {
    ($(#[$meta:meta])* $name:ident) => {
        $(#[$meta])*
        #[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
        pub struct $name(pub [u8; 16]);

        impl $name {
            /// Generates a new random id.
            pub fn random() -> Self {
                let mut bytes = [0u8; 16];
                rand::rngs::OsRng.fill_bytes(&mut bytes);
                Self(bytes)
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                for b in self.0 {
                    write!(f, "{b:02x}")?;
                }
                Ok(())
            }
        }

        impl fmt::Debug for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                write!(f, concat!(stringify!($name), "({})"), self)
            }
        }

        impl FromStr for $name {
            type Err = crate::Error;

            /// Parses the 32-character hex form produced by `Display`.
            fn from_str(s: &str) -> crate::Result<Self> {
                parse_hex16(s).map(Self)
            }
        }
    };
}

random_id! {
    /// Random identifier of a job: one user action (a drop, a Share, a download request)
    /// with its files and folders. See `docs/transfers.md`.
    ///
    /// Generated by the sender. Stable for the job's whole life, so a deferred or
    /// interrupted job is resumed by the receiver instead of being received twice.
    JobId
}

random_id! {
    /// Random, stable identifier of a shared folder (whitelist entry). See `docs/shares.md`.
    ShareId
}

fn parse_hex16(s: &str) -> crate::Result<[u8; 16]> {
    let bytes = s.as_bytes();
    if bytes.len() != 32 {
        return Err(crate::Error::InvalidId);
    }
    let mut out = [0u8; 16];
    for (i, pair) in bytes.chunks_exact(2).enumerate() {
        let hi = (pair[0] as char)
            .to_digit(16)
            .ok_or(crate::Error::InvalidId)?;
        let lo = (pair[1] as char)
            .to_digit(16)
            .ok_or(crate::Error::InvalidId)?;
        out[i] = (hi * 16 + lo) as u8;
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hex_roundtrip() {
        let id = JobId::random();
        assert_eq!(id.to_string().parse::<JobId>().unwrap(), id);
        assert!("xyz".parse::<ShareId>().is_err());
        assert!("zz".repeat(16).parse::<ShareId>().is_err());
    }
}
